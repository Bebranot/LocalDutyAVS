    public void UpdateState(LatheUpdateState state)
    {
        _entMan.TryGetComponent<LatheComponent>(Entity, out var lathe);

        var multipliersChanged = false;
        if (lathe != null
            && (!MathHelper.CloseTo(lathe.FinalMaterialMultiplier, _materialMultiplier)
                || !MathHelper.CloseTo(lathe.FinalTimeMultiplier, _timeMultiplier)))
        {
            _materialMultiplier = lathe.FinalMaterialMultiplier;
            _timeMultiplier = lathe.FinalTimeMultiplier;
            multipliersChanged = true;
        }

        UpdateBadges(state, lathe);
        SyncRecipes(state.Recipes, lathe, multipliersChanged);
        RefreshAvailability();
        ApplyFilter();
        UpdateDetail();
        UpdateQueue(state, lathe);
    }

    /// <summary>
    /// Привести строки к списку рецептов с сервера. Список меняется редко (исследование, емаг, чертёж),
    /// поэтому здесь только добавляем недостающие и убираем лишние — существующие не трогаем.
    /// </summary>
    private void SyncRecipes(List<ProtoId<LatheRecipePrototype>> recipes, LatheComponent? lathe, bool multipliersChanged)
    {
        var changed = recipes.Count != _rows.Count;
        if (!changed)
        {
            foreach (var id in recipes)
            {
                if (_rows.ContainsKey(id))
                    continue;

                changed = true;
                break;
            }
        }

        var created = new HashSet<DutyLatheRecipeRow>();
        if (changed)
        {
            var wanted = new HashSet<ProtoId<LatheRecipePrototype>>(recipes);
            foreach (var (id, row) in _rows.ToList())
            {
                if (wanted.Contains(id))
                    continue;

                if (_selected == row)
                    _selected = null;

                if (_lastClickRow == row)
                    _lastClickRow = null;

                row.Orphan();
                _rows.Remove(id);
            }

            foreach (var id in recipes)
            {
                if (_rows.ContainsKey(id) || !_proto.Resolve(id, out var proto))
                    continue;

                var row = CreateRow(proto, lathe);
                _rows[id] = row;
                created.Add(row);
            }

            _sortedRows.Clear();
            _sortedRows.AddRange(_rows.Values.OrderBy(r => r.RecipeName, StringComparer.CurrentCultureIgnoreCase));

            // Переставляем, а не пересоздаём: выход из дерева удалил бы сущность иконки и заспавнил заново.
            for (var i = 0; i < _sortedRows.Count; i++)
            {
                var row = _sortedRows[i];
                if (row.Parent == null)
                    RecipeList.AddChild(row);
                row.SetPositionInParent(i);
            }

            RebuildCategories();
        }

        if (!multipliersChanged)
            return;

        foreach (var row in _sortedRows)
        {
            if (!created.Contains(row))
                row.SetCosts(BuildCosts(row.Recipe, lathe), EstimateSeconds(row.Recipe, lathe));
        }

        _lastCostMarkup = null;
    }

    private DutyLatheRecipeRow CreateRow(LatheRecipePrototype recipe, LatheComponent? lathe)
    {
        var row = new DutyLatheRecipeRow(recipe,
            _lathe.GetRecipeName(recipe),
            _lathe.GetRecipeDescription(recipe),
            CreateIcon(recipe, 32))
        {
            Accent = _accent,
        };
        row.SetCosts(BuildCosts(recipe, lathe), EstimateSeconds(recipe, lathe));
        row.OnPressed += _ => OnRowPressed(row);
        return row;
    }

    private List<DutyLatheCost> BuildCosts(LatheRecipePrototype recipe, LatheComponent? lathe)
    {
        var multiplier = lathe?.FinalMaterialMultiplier ?? 1f;
        var costs = new List<DutyLatheCost>();

        foreach (var (id, amount) in recipe.Materials)
        {
            if (!_proto.Resolve(id, out var material))
                continue;

            var adjusted = SharedLatheSystem.AdjustMaterial(amount, recipe.ApplyMaterialDiscount, multiplier);
            var sheetVolume = Math.Max(1, _materialStorage.GetSheetVolume(material));

            if (!_materialIcons.TryGetValue(id.Id, out var icon))
            {
                icon = material.Icon == SpriteSpecifier.Invalid ? null : _sprite.Frame0(material.Icon);
                _materialIcons[id.Id] = icon;
            }

            costs.Add(new DutyLatheCost
            {
                Id = id.Id,
                Needed = adjusted,
                Shown = adjusted / (float) sheetVolume,
                PerShown = sheetVolume,
                Name = Loc.GetString(material.Name),
                Icon = icon,
                Color = material.Color,
            });
        }

        // ADT: часть рецептов протолата требует реагент из мензурки в слоте станка.
        foreach (var (reagent, needed) in recipe.ReagentCost)
        {
            if (!_proto.Resolve(reagent, out var reagentProto))
                continue;

            var adjusted = SharedLatheSystem.AdjustReagentCost(needed, recipe.ApplyMaterialDiscount, multiplier).Float();
            costs.Add(new DutyLatheCost
            {
                Id = reagent.Id,
                IsReagent = true,
                Needed = adjusted,
                Shown = adjusted,
                PerShown = 1,
                Name = reagentProto.LocalizedName,
                Color = reagentProto.SubstanceColor,
            });
        }

        return costs;
    }

    /// <summary>
    /// Время одной детали так же, как его считает сервер, но без смазки (ReagentSpeed известен только серверу) —
    /// поэтому в интерфейсе оно со знаком «≈».
    /// </summary>
    private static double EstimateSeconds(LatheRecipePrototype recipe, LatheComponent? lathe)
    {
        var seconds = recipe.CompleteTime.TotalSeconds;
        if (lathe != null)
            seconds *= Math.Pow(Math.Max(0.1f, lathe.FinalTimeMultiplier), lathe.MachinePartEfficiencyExponent);

        return Math.Max(0.1, seconds);
    }

    private Control CreateIcon(LatheRecipePrototype? recipe, float size)
    {
        var setSize = new Vector2(size, size);

        if (recipe?.Icon != null)
        {
            return new TextureRect
            {
                Texture = _sprite.Frame0(recipe.Icon),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                SetSize = setSize,
            };
        }

        if (recipe?.Result is { } result)
        {
            var view = new EntityPrototypeView
            {
                SetSize = setSize,
                Stretch = SpriteView.StretchMode.Fill,
            };
            view.SetPrototype(result);
            return view;
        }

        // Рецепты-жидкости (биогенератор): иконки нет — показываем цвет первого реагента.
        if (recipe?.ResultReagents is { Count: > 0 } reagents
            && _proto.TryIndex(reagents.Keys.First(), out var reagent))
        {
            return new PanelContainer
            {
                SetSize = setSize * 0.6f,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                PanelOverride = new StyleBoxFlat { BackgroundColor = reagent.SubstanceColor },
            };
        }

        return new Control { SetSize = setSize };
    }

