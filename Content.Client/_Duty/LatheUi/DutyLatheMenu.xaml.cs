    /// <summary>
    /// Перекрасить строки по наличию материалов. Количество каждого материала спрашиваем один раз,
    /// а не на каждый рецепт, как это делал CanProduce. Возвращает true, если у какой-то строки сменилась доступность.
    /// </summary>
    private bool RefreshAvailability()
    {
        _materialAmounts.Clear();
        foreach (var row in _sortedRows)
        {
            foreach (var cost in row.Costs)
            {
                if (!cost.IsReagent && !_materialAmounts.ContainsKey(cost.Id))
                    _materialAmounts[cost.Id] = _materialStorage.GetMaterialAmount(Entity, cost.Id);
            }
        }

        _beakerSolution = GetBeakerSolution();

        var changed = false;
        foreach (var row in _sortedRows)
        {
            changed |= row.RefreshAvailability(_materialAmounts, _beakerSolution, _amount);
        }

        return changed;
    }

    private Solution? GetBeakerSolution()
    {
        if (!_entMan.TryGetComponent<LatheComponent>(Entity, out var lathe)
            || lathe.ReagentCostSlotId is not { } slotId
            || _itemSlots.GetItemOrNull(Entity, slotId) is not { } beaker
            || !_solution.TryGetFitsInDispenser(beaker, out _, out var solution))
        {
            return null;
        }

        return solution;
    }

    private void OnRowPressed(DutyLatheRecipeRow row)
    {
        var now = _timing.RealTime;
        if (_lastClickRow == row && now - _lastClickTime <= DoubleClickTime)
        {
            _lastClickRow = null;
            Select(row);
            QueueSelected();
            return;
        }

        _lastClickRow = row;
        _lastClickTime = now;
        Select(row);
    }

    private void Select(DutyLatheRecipeRow row)
    {
        if (_selected != null)
            _selected.Selected = false;

        _selected = row;
        row.Selected = true;
        UpdateDetail();
    }

    private void QueueSelected()
    {
        if (_selected == null || !_selected.CanProduce)
            return;

        RecipeQueueAction?.Invoke(_selected.Recipe.ID, _amount);
    }

    private void UpdateDetail()
    {
        var row = _selected;
        DetailHint.Visible = row == null;
        DetailBody.Visible = row != null;
        QueueButton.Disabled = row == null || !row.CanProduce;
        QueueButton.Text = _amount > 1
            ? Loc.GetString("duty-lathe-to-queue-many", ("amount", _amount))
            : Loc.GetString("duty-lathe-to-queue");

        if (row == null)
        {
            DetailTime.Text = string.Empty;
            _detailRecipe = null;
            return;
        }

        if (_detailRecipe != row.Recipe.ID)
        {
            _detailRecipe = row.Recipe.ID;
            _lastCostMarkup = null;
            DetailIcon.RemoveAllChildren();
            DetailIcon.AddChild(CreateIcon(row.Recipe, 64));
            DetailName.Text = row.RecipeName;
            DetailName.ToolTip = row.RecipeName;

            var description = _lathe.GetRecipeDescription(row.Recipe);
            DetailDescription.SetMarkupPermissive(string.IsNullOrWhiteSpace(description)
                ? string.Empty
                : $"[italic]{FormattedMessage.EscapeText(description)}[/italic]");
        }

        var markup = BuildCostMarkup(row);
        if (markup != _lastCostMarkup)
        {
            _lastCostMarkup = markup;
            DetailCost.SetMarkupPermissive(markup);
        }

        DetailTime.Text = Loc.GetString("duty-lathe-time-total", ("time", DutyLatheStyle.FormatTime(row.ItemSeconds * _amount)));
    }

    private string BuildCostMarkup(DutyLatheRecipeRow row)
    {
        var sb = new StringBuilder();
        sb.Append(Loc.GetString("duty-lathe-cost-title", ("amount", _amount)));

        if (row.Costs.Count == 0)
            sb.Append(' ').Append(Loc.GetString("duty-lathe-cost-free"));

        var first = true;
        foreach (var cost in row.Costs)
        {
            sb.Append(first ? " " : "  ·  ");
            first = false;

            var name = FormattedMessage.EscapeText(cost.Name);
            if (cost.IsReagent && _beakerSolution == null)
            {
                sb.Append(Loc.GetString("duty-lathe-cost-reagent-no-beaker",
                    ("name", name),
                    ("need", DutyLatheStyle.FormatAmount(cost.Shown * _amount))));
                continue;
            }

            var have = DutyLatheRecipeRow.Have(cost, _materialAmounts, _beakerSolution) / cost.PerShown;
            var enough = DutyLatheRecipeRow.HasEnough(cost, _materialAmounts, _beakerSolution, _amount);
            sb.Append(Loc.GetString(cost.IsReagent ? "duty-lathe-cost-reagent" : "duty-lathe-cost-material",
                ("name", name),
                ("need", DutyLatheStyle.FormatAmount(cost.Shown * _amount)),
                ("have", DutyLatheStyle.FormatAmount(have)),
                ("color", (enough ? DutyLatheStyle.Good : DutyLatheStyle.Bad).ToHex())));
        }

        if (!row.CanProduce)
            sb.Append('\n').Append(Loc.GetString("duty-lathe-cost-not-enough"));

        return sb.ToString();
    }

