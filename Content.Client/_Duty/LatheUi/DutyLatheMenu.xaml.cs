    #region Количество

    private void SetAmount(int amount)
    {
        amount = Math.Clamp(amount, 1, SharedLatheSystem.MaxItemsPerRequest);
        SetAmountText(amount);

        if (_amount == amount)
            return;

        _amount = amount;
        if (RefreshAvailability() || _currentCategory == CategoryAvailable || _onlyAvailable)
            ApplyFilter();
        UpdateDetail();
    }

    private void SetAmountText(int amount)
    {
        _settingAmountText = true;
        AmountLineEdit.Text = amount.ToString();
        _settingAmountText = false;
    }

    private void OnAmountTyped()
    {
        if (_settingAmountText)
            return;

        // Пока игрок печатает (пустое поле, «0»), текст не трогаем — только количество.
        if (!int.TryParse(AmountLineEdit.Text, out var amount))
            return;

        if (amount > SharedLatheSystem.MaxItemsPerRequest)
        {
            SetAmount(amount);
            return;
        }

        amount = Math.Max(1, amount);
        if (_amount == amount)
            return;

        _amount = amount;
        if (RefreshAvailability() || _currentCategory == CategoryAvailable || _onlyAvailable)
            ApplyFilter();
        UpdateDetail();
    }

