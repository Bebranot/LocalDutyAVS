    #region Очередь

    private void UpdateQueue(LatheUpdateState state, LatheComponent? lathe)
    {
        _queue = state.Queue;
        _productionStart = state.ProductionStart;
        _productionLength = state.ProductionLength;

        LatheRecipePrototype? current = null;
        var producing = state.ProductionStart != null
                        && state.CurrentlyProducing is { } currentId
                        && _proto.Resolve(currentId, out current);

        CurrentPanel.Visible = producing;
        if (producing && current != null)
        {
            if (_currentIconRecipe != current.ID)
            {
                _currentIconRecipe = current.ID;
                CurrentIcon.RemoveAllChildren();
                CurrentIcon.AddChild(CreateIcon(current, 32));
            }

            var name = _lathe.GetRecipeName(current);
            CurrentName.Text = name;
            CurrentName.ToolTip = name;
        }

        // Очередь есть, а печать не идёт — сервер не запускает станок только без питания.
        PowerWarningLabel.Visible = !producing && _queue.Length > 0;
        QueueEmptyLabel.Visible = !producing && _queue.Length == 0;
        ClearQueueButton.Disabled = _queue.Length == 0;

        _queuedSeconds = 0;
        for (var i = 0; i < _queue.Length; i++)
        {
            var batch = _queue[i];
            _proto.Resolve(batch.Recipe, out var recipe);

            // ItemsPrinted уже включает деталь, которая сейчас в работе.
            var remaining = Math.Max(0, batch.ItemsRequested - batch.ItemsPrinted);
            var seconds = recipe != null ? remaining * EstimateSeconds(recipe, lathe) : 0;
            _queuedSeconds += seconds;

            var progress = seconds > 0
                ? Loc.GetString("duty-lathe-batch-progress-time",
                    ("printed", batch.ItemsPrinted),
                    ("total", batch.ItemsRequested),
                    ("time", DutyLatheStyle.FormatTime(seconds)))
                : Loc.GetString("duty-lathe-batch-progress",
                    ("printed", batch.ItemsPrinted),
                    ("total", batch.ItemsRequested));

            if (i >= _queueRows.Count)
                _queueRows.Add(CreateQueueRow());

            var name = recipe != null ? _lathe.GetRecipeName(recipe) : batch.Recipe.Id;
            _queueRows[i].Set(i, _queue.Length, batch.Recipe.Id, name, progress, () => CreateIcon(recipe, 32));
        }

        for (var i = _queueRows.Count - 1; i >= _queue.Length; i--)
        {
            _queueRows[i].Orphan();
            _queueRows.RemoveAt(i);
        }

        _lastCurrentSeconds = -1;
        _lastTotalSeconds = -1;
        UpdateTimers();
    }

    private DutyLatheQueueRow CreateQueueRow()
    {
        var row = new DutyLatheQueueRow();
        row.OnMoveUp += index => QueueMoveUpAction?.Invoke(index);
        row.OnMoveDown += index => QueueMoveDownAction?.Invoke(index);
        row.OnDelete += index => QueueDeleteAction?.Invoke(index);
        QueueList.AddChild(row);
        return row;
    }

    private void ClearQueue()
    {
        // Удаляем всегда нулевую партию: если пока идут сообщения какая-то партия допечатается,
        // индексы сдвинутся, а «первая» останется первой. Материалы сервер возвращает сам.
        for (var i = 0; i < _queue.Length; i++)
        {
            QueueDeleteAction?.Invoke(0);
        }
    }

    /// <summary>
    /// Прогресс текущей детали и общее время. Сервер присылает только момент старта и длительность,
    /// дальше тикаем на клиенте; тексты меняем, только когда сменилась секунда.
    /// </summary>
    private void UpdateTimers()
    {
        var currentRemaining = 0.0;
        if (CurrentPanel.Visible && _productionStart is { } start)
        {
            var elapsed = (_timing.CurTime - start).TotalSeconds;
            var length = _productionLength.TotalSeconds;
            CurrentProgress.Value = length > 0 ? (float) Math.Clamp(elapsed / length, 0, 1) : 1f;
            currentRemaining = Math.Max(0, length - elapsed);

            var seconds = (int) Math.Ceiling(currentRemaining);
            if (seconds != _lastCurrentSeconds)
            {
                _lastCurrentSeconds = seconds;
                CurrentStatus.Text = Loc.GetString("duty-lathe-producing", ("time", DutyLatheStyle.FormatTime(seconds)));
            }
        }

        var total = (int) Math.Ceiling(currentRemaining + _queuedSeconds);
        if (total == _lastTotalSeconds)
            return;

        _lastTotalSeconds = total;
        QueueTotalLabel.Text = total > 0
            ? Loc.GetString("duty-lathe-queue-total", ("time", DutyLatheStyle.FormatTime(total)))
            : string.Empty;
    }

    #endregion

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        UpdateTimers();

        _availabilityAccumulator += args.DeltaSeconds;
        if (_availabilityAccumulator < AvailabilityRefreshInterval)
            return;

        _availabilityAccumulator = 0;
        if (RefreshAvailability())
            ApplyFilter();

        if (_selected != null)
            UpdateDetail();
    }

    /// <summary>
    /// Размер запоминаем при закрытии: и крестиком, и когда игрок отошёл от станка (BUI закрывает окно сам).
    /// </summary>
    protected override void ExitedTree()
    {
        base.ExitedTree();

        var size = Size;
        if (size.X <= 0 || size.Y <= 0 || (size - _savedSize).LengthSquared() < 1f)
            return;

        _savedSize = size;
        _cfg.SetCVar(DutyCCVars.LatheUiWidth, size.X);
        _cfg.SetCVar(DutyCCVars.LatheUiHeight, size.Y);
        _cfg.SaveToFile();
    }
