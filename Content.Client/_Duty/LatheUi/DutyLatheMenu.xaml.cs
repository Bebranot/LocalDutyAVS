    private void RebuildCategories()
    {
        CategoryList.RemoveAllChildren();
        _categoryButtons.Clear();

        AddCategoryButton(CategoryAll, Loc.GetString("duty-lathe-category-all"));
        AddCategoryButton(CategoryAvailable, Loc.GetString("duty-lathe-category-available"));
        CategoryList.AddChild(new Control { MinHeight = 6 });

        var categories = new HashSet<ProtoId<LatheCategoryPrototype>>();
        var hasOther = false;
        foreach (var row in _sortedRows)
        {
            if (row.Recipe.Categories.Count == 0)
                hasOther = true;
            else
                categories.UnionWith(row.Recipe.Categories);
        }

        var sorted = new List<(string Id, string Name)>();
        foreach (var id in categories)
        {
            if (_proto.Resolve(id, out var category))
                sorted.Add((category.ID, Loc.GetString(category.Name)));
        }

        sorted.Sort((a, b) => string.Compare(a.Name, b.Name, StringComparison.CurrentCultureIgnoreCase));
        foreach (var (id, name) in sorted)
        {
            AddCategoryButton(id, name);
        }

        if (hasOther)
            AddCategoryButton(CategoryOther, Loc.GetString("duty-lathe-category-other"));

        if (!_categoryButtons.ContainsKey(_currentCategory))
            _currentCategory = CategoryAll;

        UpdateCategorySelection();
    }

    private void AddCategoryButton(string key, string name)
    {
        var button = new DutyLatheCategoryButton(key, name) { Accent = _accent };
        button.OnPressed += _ =>
        {
            _currentCategory = key;
            UpdateCategorySelection();
            ApplyFilter();
        };
        CategoryList.AddChild(button);
        _categoryButtons[key] = button;
    }

    private void UpdateCategorySelection()
    {
        foreach (var (key, button) in _categoryButtons)
        {
            button.Selected = key == _currentCategory;
        }
    }

    private void OnSearchChanged()
    {
        _searchTokens = DutyLatheSearch.Normalize(SearchBar.Text)
            .Split(' ', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        ApplyFilter();
    }

    /// <summary>
    /// Один проход по строкам: видимость + счётчики категорий. Ничего не создаётся и не удаляется,
    /// поэтому поиск не лагает даже на техфабе с сотнями рецептов.
    /// </summary>
    private void ApplyFilter()
    {
        _categoryCounts.Clear();
        var total = 0;
        var available = 0;
        var other = 0;
        var visible = 0;

        foreach (var row in _sortedRows)
        {
            var match = MatchesSearch(row) && (!_onlyAvailable || row.CanProduce);
            if (match)
            {
                total++;
                if (row.CanProduce)
                    available++;

                if (row.Recipe.Categories.Count == 0)
                    other++;

                foreach (var category in row.Recipe.Categories)
                {
                    _categoryCounts[category.Id] = _categoryCounts.GetValueOrDefault(category.Id) + 1;
                }
            }

            var show = match && _currentCategory switch
            {
                CategoryAll => true,
                CategoryAvailable => row.CanProduce,
                CategoryOther => row.Recipe.Categories.Count == 0,
                _ => HasCategory(row, _currentCategory),
            };

            row.Visible = show;
            if (show)
                visible++;
        }

        foreach (var (key, button) in _categoryButtons)
        {
            button.SetCount(key switch
            {
                CategoryAll => total,
                CategoryAvailable => available,
                CategoryOther => other,
                _ => _categoryCounts.GetValueOrDefault(key),
            });
        }

        NoResultsLabel.Visible = visible == 0;
    }

    private bool MatchesSearch(DutyLatheRecipeRow row)
    {
        // Все слова запроса в любом порядке: «5.45 бронеб» найдёт «Коробка 5.45×39 бронебойные».
        foreach (var token in _searchTokens)
        {
            if (!row.SearchText.Contains(token, StringComparison.Ordinal))
                return false;
        }

        return true;
    }

    private static bool HasCategory(DutyLatheRecipeRow row, string category)
    {
        foreach (var id in row.Recipe.Categories)
        {
            if (id.Id == category)
                return true;
        }

        return false;
    }

    private void SelectFirstVisible()
    {
        foreach (var row in _sortedRows)
        {
            if (!row.Visible)
                continue;

            Select(row);
            return;
        }
    }

