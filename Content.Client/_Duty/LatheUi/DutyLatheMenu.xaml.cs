    private void UpdateBadges(LatheUpdateState state, LatheComponent? lathe)
    {
        BadgeContainer.RemoveAllChildren();

        var accent = DutyLatheStyle.DefaultAccent;
        var accentSet = false;
        foreach (var channelId in state.AnnounceChannels)
        {
            if (!_proto.TryIndex(channelId, out var channel))
                continue;

            if (!accentSet)
            {
                accent = channel.Color;
                accentSet = true;
            }

            AddBadge(Loc.GetString("duty-lathe-badge-announce", ("channel", channel.LocalizedName)),
                Loc.GetString("duty-lathe-badge-announce-tooltip", ("channel", channel.LocalizedName)),
                channel.Color);
        }

        SetAccent(accent);

        if (lathe == null)
            return;

        if (lathe.DynamicPacks.Count > 0)
        {
            AddBadge(Loc.GetString("duty-lathe-badge-research"),
                Loc.GetString("duty-lathe-badge-research-tooltip"),
                Color.FromHex("#9FB6FF"));
        }

        if (_entMan.HasComponent<BlueprintReceiverComponent>(Entity))
        {
            AddBadge(Loc.GetString("duty-lathe-badge-blueprint"),
                Loc.GetString("duty-lathe-badge-blueprint-tooltip"),
                Color.FromHex("#8FD3FF"));
        }

        if (state.HasReagentSlot)
        {
            AddBadge(Loc.GetString(state.BeakerInserted ? "duty-lathe-badge-beaker-in" : "duty-lathe-badge-beaker-out"),
                Loc.GetString("duty-lathe-badge-beaker-tooltip"),
                state.BeakerInserted ? DutyLatheStyle.Good : DutyLatheStyle.Bad);
        }

        if (lathe.ReagentOutputSlotId != null)
        {
            AddBadge(Loc.GetString("duty-lathe-badge-reagent-output"),
                Loc.GetString("duty-lathe-badge-reagent-output-tooltip"),
                Color.FromHex("#B0E0A0"));
        }

        if (!lathe.SuppressMachinePartUpgrades && lathe.FinalTimeMultiplier > 0f)
        {
            var speed = (int) MathF.Round(lathe.TimeMultiplier / lathe.FinalTimeMultiplier * 100f);
            var cost = (int) MathF.Round(lathe.FinalMaterialMultiplier / MathF.Max(0.01f, lathe.MaterialUseMultiplier) * 100f);
            if (speed != 100 || cost != 100)
            {
                AddBadge(Loc.GetString("duty-lathe-badge-parts", ("speed", speed), ("cost", cost)),
                    Loc.GetString("duty-lathe-badge-parts-tooltip"),
                    DutyLatheStyle.TextMuted);
            }
        }
    }

