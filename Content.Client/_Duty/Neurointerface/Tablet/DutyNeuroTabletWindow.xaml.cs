/// <summary>
/// _Duty: декоративный слой тонких сканлайнов поверх тактического планшета (не перехватывает ввод).
/// </summary>
public sealed class DutyNeuroScanlineOverlay : Control
{
    private static readonly Color ScanlineColor = Color.FromHex("#C82337").WithAlpha(0.03f);

    public DutyNeuroScanlineOverlay()
    {
        MouseFilter = MouseFilterMode.Ignore;
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        var w = PixelWidth;
        var h = PixelHeight;
        if (w <= 0f || h <= 0f)
            return;

        var step = MathF.Max(3f, 4f * UIScale);
        for (var y = 0f; y < h; y += step)
        {
            handle.DrawRect(new UIBox2(0f, y, w, y + 1f), ScanlineColor);
        }
    }
}
