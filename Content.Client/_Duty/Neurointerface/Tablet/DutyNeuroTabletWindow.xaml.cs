    private void UpdateLiveTimers()
    {
        // Строки таймеров видимы только на своей вкладке; при переключении SwitchTab вызовет метод снова.
        if (_activeTab != TabletTab.Timers)
            return;

        foreach (var row in _timerRows)
        {
            var entry = row.Entry;
            var seconds = GetRemainingSeconds(entry);
            if (seconds != row.LastSeconds)
            {
                row.LastSeconds = seconds;
                row.TimeLabel.Text = FormatTimerMmSs(seconds);
            }

            var finished = entry.Status == DutyNeuroTimerStatus.Running && seconds <= 0;
            if (row.LastFinished == finished)
                continue;

            row.LastFinished = finished;
            if (finished)
            {
                row.StatusLabel.Text = Loc.GetString("duty-neuro-tablet-timer-finished");
                row.StatusLabel.FontColorOverride = AccentCrimsonColor;
                row.TimeLabel.FontColorOverride = AccentCrimsonColor;
            }
            else
            {
                row.StatusLabel.Text = GetTimerStatusText(entry.Status);
                row.StatusLabel.FontColorOverride = GetTimerStatusColor(entry.Status);
                row.TimeLabel.FontColorOverride = entry.Status == DutyNeuroTimerStatus.Running
                    ? AccentOrangeColor
                    : TextPrimaryColor;
            }
        }
    }

    /// <summary>
    /// Оставшееся время в целых секундах, округлённое вверх: 60 с показывает 01:00, а не 00:59.
    /// </summary>
    private int GetRemainingSeconds(DutyNeuroTimerEntry timer)
    {
        return (int) Math.Ceiling(GetTimerRemaining(timer).TotalSeconds);
    }

    private TimeSpan GetTimerRemaining(DutyNeuroTimerEntry timer)
    {
        var rem = timer.Status switch
        {
            DutyNeuroTimerStatus.Running when timer.EndTime.HasValue => timer.EndTime.Value - _timing.CurTime,
            DutyNeuroTimerStatus.Paused => timer.RemainingWhenPaused ?? timer.Duration,
            _ => timer.Duration
        };

        return rem > TimeSpan.Zero ? rem : TimeSpan.Zero;
    }

