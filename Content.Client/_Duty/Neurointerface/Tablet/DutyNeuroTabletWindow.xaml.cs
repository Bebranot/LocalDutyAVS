    /// <summary>
    /// Обновляет интерфейс планшета по присланному состоянию с сервера.
    /// Списки пересобираются только если их данные реально изменились.
    /// </summary>
    public void UpdateState(DutyNeuroTabletBuiState state)
    {
        var old = _state;
        _state = state;

        // Сервер подтвердил выбор (или ответ не пришёл слишком долго) — оптимистичную подсветку сбрасываем.
        if (_optimisticSquadId != null &&
            (state.ActiveSquadId == _optimisticSquadId ||
             _timing.RealTime - _optimisticAt > OptimisticSelectTimeout))
        {
            _optimisticSquadId = null;
        }

        if (!string.IsNullOrWhiteSpace(state.StationName) && old?.StationName != state.StationName)
            StationNameLabel.Text = state.StationName.ToUpperInvariant();

        if (old == null || old.AlertCodeName != state.AlertCodeName || old.AlertCodeColor != state.AlertCodeColor)
        {
            AlertCodeLabel.Text = Loc.GetString(
                "duty-neuro-tablet-alert-code",
                ("name", state.AlertCodeName.ToUpperInvariant()));
            AlertCodeLabel.FontColorOverride = state.AlertCodeColor;
            AlertBadgePanel.PanelOverride = CreateBox(
                state.AlertCodeColor.WithAlpha(0.14f),
                state.AlertCodeColor.WithAlpha(0.75f),
                1);
        }

        // Вторжение «Червя ICE» в отряд — кнопка перезапуска сети загорается тревогой.
        if (_rebootHighlighted != state.NetworkIntrusion)
            StyleRebootButton(state.NetworkIntrusion);

        if (_entMan.TryGetEntity(state.TargetGrid, out var gridUid) && NavMap.MapUid != gridUid)
        {
            NavMap.MapUid = gridUid;
            NavMap.ForceNavMapUpdate();
        }

        var activeSquad = GetActiveSquad(state);
        var activeId = activeSquad?.SquadId ?? string.Empty;
        var activeChanged = activeId != _lastActiveSquadId;
        _lastActiveSquadId = activeId;

        if (string.IsNullOrEmpty(_expandedSquadId))
            _expandedSquadId = activeId;

        var squadsChanged = old == null || !SquadsEqual(old.Squads, state.Squads);
        var ordersChanged = old == null || !old.Orders.SequenceEqual(state.Orders);

        if (squadsChanged || ordersChanged || activeChanged)
            NavMap.SetOverlayData(activeSquad?.Members ?? EmptyMembers, state.Orders);

        if (squadsChanged || activeChanged)
            _dirty |= DirtyParts.MonitorSquads | DirtyParts.SquadsTab | DirtyParts.Crew;

        if (ordersChanged)
            _dirty |= DirtyParts.ActiveOrders;

        if (old == null || !old.CrewCandidates.SequenceEqual(state.CrewCandidates))
            _dirty |= DirtyParts.Crew;

        if (old == null || !old.Timers.SequenceEqual(state.Timers))
            _dirty |= DirtyParts.Timers;

        if (old == null || !old.Tasks.SequenceEqual(state.Tasks))
            _dirty |= DirtyParts.Tasks;

        FlushDirty();
    }

    /// <summary>
    /// Пересобирает помеченные списки видимой вкладки; скрытые ждут переключения на свою вкладку.
    /// </summary>
    private void FlushDirty()
    {
        if (_dirty == DirtyParts.None || _state == null)
            return;

        switch (_activeTab)
        {
            case TabletTab.Monitor:
                if ((_dirty & DirtyParts.MonitorSquads) != 0)
                    RebuildMonitorSquads();
                if ((_dirty & DirtyParts.ActiveOrders) != 0)
                    RebuildActiveOrders();
                _dirty &= ~(DirtyParts.MonitorSquads | DirtyParts.ActiveOrders);
                break;
            case TabletTab.Squads:
                if ((_dirty & DirtyParts.SquadsTab) != 0)
                    RebuildSquadsTab();
                if ((_dirty & DirtyParts.Crew) != 0)
                    RebuildCrewCandidates();
                _dirty &= ~(DirtyParts.SquadsTab | DirtyParts.Crew);
                break;
            case TabletTab.Timers:
                if ((_dirty & DirtyParts.Timers) != 0)
                    RebuildTimersTab();
                _dirty &= ~DirtyParts.Timers;
                break;
            case TabletTab.Tasks:
                if ((_dirty & DirtyParts.Tasks) != 0)
                    RebuildTasksTab();
                _dirty &= ~DirtyParts.Tasks;
                break;
        }
    }

    private static bool SquadsEqual(List<DutyNeuroSquadSummary> a, List<DutyNeuroSquadSummary> b)
    {
        if (a.Count != b.Count)
            return false;

        // Запись сравнивает List<Members> по ссылке, поэтому состав сверяем поэлементно.
        for (var i = 0; i < a.Count; i++)
        {
            var x = a[i];
            var y = b[i];
            if (x.SquadId != y.SquadId ||
                x.Callsign != y.Callsign ||
                x.AliveCount != y.AliveCount ||
                x.TotalCount != y.TotalCount ||
                x.LeaderName != y.LeaderName ||
                !x.Members.SequenceEqual(y.Members))
            {
                return false;
            }
        }

        return true;
    }

    /// <summary>
    /// Выбор отряда: подсвечиваем сразу локально и шлём команду, state с сервера подтвердит позже.
    /// </summary>
    private void SelectSquad(string squadId)
    {
        _expandedSquadId = squadId;
        _optimisticSquadId = squadId;
        _optimisticAt = _timing.RealTime;
        OnSelectSquad?.Invoke(squadId);

        if (_state == null)
            return;

        var active = GetActiveSquad(_state);
        _lastActiveSquadId = active?.SquadId ?? string.Empty;
        NavMap.SetOverlayData(active?.Members ?? EmptyMembers, _state.Orders);
        // Пересборку делает FrameUpdate: нельзя заменять кнопку внутри её же обработчика нажатия.
        _dirty |= DirtyParts.MonitorSquads | DirtyParts.SquadsTab | DirtyParts.Crew;
    }

