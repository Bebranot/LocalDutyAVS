    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        float w = PixelWidth;
        float h = PixelHeight;
        if (w <= 0f || h <= 0f)
            return;

        if (w != _frameW || h != _frameH || UIScale != _frameScale)
            RebuildFrame(w, h);

        handle.DrawPrimitives(DrawPrimitiveTopology.TriangleFan, _frameOuter, WindowBgColor);
        handle.DrawPrimitives(DrawPrimitiveTopology.LineStrip, _frameOuterStroke, BorderRedColor);
        handle.DrawPrimitives(DrawPrimitiveTopology.LineStrip, _frameInnerStroke, BorderDimRedColor);
    }

    private void RebuildFrame(float w, float h)
    {
        _frameW = w;
        _frameH = h;
        _frameScale = UIScale;

        var c1 = 14f * UIScale; // большой скос (верх-лево, низ-право)
        var c2 = 8f * UIScale;  // малый скос (верх-право, низ-лево)

        var outer = _frameOuter;
        outer[0] = new Vector2(c1, 0f);
        outer[1] = new Vector2(w - c2, 0f);
        outer[2] = new Vector2(w, c2);
        outer[3] = new Vector2(w, h - c1);
        outer[4] = new Vector2(w - c1, h);
        outer[5] = new Vector2(c2, h);
        outer[6] = new Vector2(0f, h - c2);
        outer[7] = new Vector2(0f, c1);

        for (var i = 0; i < 8; i++)
            _frameOuterStroke[i] = outer[i];
        _frameOuterStroke[8] = outer[0];

        var inset = 3f * UIScale;
        var inner = _frameInnerStroke;
        inner[0] = new Vector2(c1 + inset * 0.5f, inset);
        inner[1] = new Vector2(w - c2 - inset * 0.5f, inset);
        inner[2] = new Vector2(w - inset, c2 + inset * 0.5f);
        inner[3] = new Vector2(w - inset, h - c1 - inset * 0.5f);
        inner[4] = new Vector2(w - c1 - inset * 0.5f, h - inset);
        inner[5] = new Vector2(c2 + inset * 0.5f, h - inset);
        inner[6] = new Vector2(inset, h - c2 - inset * 0.5f);
        inner[7] = new Vector2(inset, c1 + inset * 0.5f);
        inner[8] = inner[0];
    }

