    private static void StyleButton(Button button, Color bg, Color border, Color textColor, Font font)
    {
        var box = new StyleBoxFlat
        {
            BackgroundColor = bg,
            BorderColor = border,
            BorderThickness = new Thickness(1f)
        };
        box.SetContentMarginOverride(StyleBox.Margin.Horizontal, 8f);
        box.SetContentMarginOverride(StyleBox.Margin.Vertical, 3f);

        button.StyleBoxOverride = box;
        button.ModulateSelfOverride = Color.White;

        if (button.Label != null)
        {
            button.Label.FontOverride = font;
            button.Label.FontColorOverride = textColor;
        }
    }

    private static StyleBoxFlat CreateFlat(Color bg)
    {
        return new StyleBoxFlat { BackgroundColor = bg };
    }

