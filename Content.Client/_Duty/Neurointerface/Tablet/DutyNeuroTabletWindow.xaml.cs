            active ? Color.White : TextMutedColor,
            _fontBold10);
    }

    private void SubmitCreateSquad()
    {
        var callsign = NewSquadInput.Text.Trim();
        if (string.IsNullOrEmpty(callsign))
            return;

        OnCreateSquad?.Invoke(callsign);
        NewSquadInput.Text = string.Empty;
    }

    private void SubmitRenameSquad()
    {
        var squadId = _state == null ? null : GetActiveSquad(_state)?.SquadId;
        if (string.IsNullOrEmpty(squadId))
            return;

        var newCallsign = RenameSquadInput.Text.Trim();
        if (string.IsNullOrEmpty(newCallsign))
            return;

        OnRenameSquad?.Invoke(squadId, newCallsign);
        RenameSquadInput.Text = string.Empty;
    }

    private void SubmitCreateTimer()
    {
        // Невалидный ввод не подменяем молча значением по умолчанию: подсвечиваем поле и ничего не шлём.
        if (!int.TryParse(TimerSecondsInput.Text.Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var seconds) ||
            seconds < 5 || seconds > 3600)
        {
            TimerSecondsInput.ModulateSelfOverride = InvalidInputColor;
            return;
        }

        var title = TimerTitleInput.Text.Trim();
        if (string.IsNullOrEmpty(title))
            title = Loc.GetString("duty-neuro-tablet-timer-default-title", ("seconds", seconds));

        OnCreateTimer?.Invoke(title, seconds);
        TimerTitleInput.Text = string.Empty;
    }

    private void SubmitCreateTask()
    {
        var title = TaskTitleInput.Text.Trim();
        if (string.IsNullOrEmpty(title))
            return;

        var desc = TaskDescInput.Text.Trim();
        var assignee = TaskAssigneeInput.Text.Trim();

        OnCreateTask?.Invoke(title, desc, assignee, _selectedTaskPriority);
        TaskTitleInput.Text = string.Empty;
        TaskDescInput.Text = string.Empty;
    }

    /// <summary>
    /// Единственный источник «активного отряда» для всего окна: локальный оптимистичный выбор,
    /// затем отряд из state, затем первый в списке (так же, как подсвечивается в UI).
    /// </summary>
    private DutyNeuroSquadSummary? GetActiveSquad(DutyNeuroTabletBuiState state)
    {
        if (_optimisticSquadId != null)
        {
            foreach (var squad in state.Squads)
            {
                if (squad.SquadId == _optimisticSquadId)
                    return squad;
            }
        }

        foreach (var squad in state.Squads)
        {
            if (squad.SquadId == state.ActiveSquadId)
                return squad;
        }

        return state.Squads.Count > 0 ? state.Squads[0] : null;
    }

