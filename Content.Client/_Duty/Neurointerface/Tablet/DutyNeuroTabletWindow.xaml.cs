    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _titleScramble.Update(args.DeltaSeconds);
        var title = _titleScramble.CurrentText;
        if (title != _lastTitleText)
        {
            _lastTitleText = title;
            HeaderTitleLabel.Text = title;
        }

        var zoomTenths = (int) MathF.Round(NavMap.ZoomFactor * 10f);
        if (zoomTenths != _lastZoomTenths)
        {
            _lastZoomTenths = zoomTenths;
            ZoomValueLabel.Text = Loc.GetString("duty-neuro-tablet-zoom", ("value", NavMap.FormattedZoom));
        }

        FlushDirty();
        UpdateLiveTimers();
    }

