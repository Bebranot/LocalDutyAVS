    private void ShowDetails(ProtoId<TraitPrototype>? id)
    {
        _detailsTrait = id;

        if (id is not { } traitId || !_prototype.TryIndex(traitId, out var trait))
        {
            DetailName.Text = Loc.GetString("duty-traits-details-empty-title");
            DetailCost.Text = string.Empty;
            DetailDescription.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("duty-traits-details-empty")));
            DetailMeta.SetMessage(new FormattedMessage());
            return;
        }

        DetailName.Text = NameOf(trait);
        DetailCost.Text = trait.Cost switch
        {
            > 0 => Loc.GetString("duty-traits-cost-spend", ("cost", trait.Cost)),
            < 0 => Loc.GetString("duty-traits-cost-grant", ("cost", -trait.Cost)),
            _ => Loc.GetString("duty-traits-cost-free"),
        };

        var description = trait.Description is { } desc ? Loc.GetString(desc) : string.Empty;
        DetailDescription.SetMessage(FormattedMessage.FromMarkupPermissive(description));

        var meta = new FormattedMessage();

        if (_prototype.TryIndex(trait.Category, out var category))
        {
            var limits = new List<string>();
            if (category.MaxTraits is { } maxTraits)
                limits.Add(Loc.GetString("duty-traits-limit-traits", ("max", maxTraits)));
            if (category.MaxPoints is { } maxPoints)
                limits.Add(Loc.GetString("duty-traits-limit-points", ("max", maxPoints)));

            meta.AddText(Loc.GetString("duty-traits-meta-category", ("category", Loc.GetString(category.Name))));
            if (limits.Count > 0)
                meta.AddText($" ({string.Join(", ", limits)})");
            meta.PushNewline();
        }

        // Конфликты: берём в обе стороны, выбранные подсвечиваем.
        var conflicting = _prototype.EnumeratePrototypes<TraitPrototype>()
            .Where(other => other.ID != trait.ID && (trait.Conflicts.Contains(other.ID) || other.Conflicts.Contains(trait.ID)))
            .Where(other => _cards.ContainsKey(other.ID))
            .OrderBy(NameOf, StringComparer.CurrentCultureIgnoreCase)
            .ToList();

        if (conflicting.Count > 0)
        {
            meta.AddText(Loc.GetString("duty-traits-meta-conflicts") + " ");
            for (var i = 0; i < conflicting.Count; i++)
            {
                var other = conflicting[i];
                var taken = _selected.Contains(other.ID);
                if (taken)
                    meta.PushColor(Color.FromHex("#f87171"));
                meta.AddText(NameOf(other));
                if (taken)
                    meta.Pop();
                if (i < conflicting.Count - 1)
                    meta.AddText(", ");
            }

            meta.PushNewline();
        }

        if (trait.SpeciesWhitelist.Count > 0)
            AddLine(meta, Loc.GetString("duty-traits-meta-species-only", ("species", SpeciesNames(trait.SpeciesWhitelist))));
        if (trait.SpeciesBlacklist.Count > 0)
            AddLine(meta, Loc.GetString("duty-traits-meta-species-not", ("species", SpeciesNames(trait.SpeciesBlacklist))));

        if (trait.JobWhitelist.Count > 0)
            AddLine(meta, Loc.GetString("duty-traits-meta-jobs-only", ("jobs", JobNames(trait.JobWhitelist))));
        if (trait.JobBlacklist.Count > 0)
            AddLine(meta, Loc.GetString("duty-traits-meta-jobs-not", ("jobs", JobNames(trait.JobBlacklist))));

        if (_blocked.TryGetValue(trait.ID, out var blockReason))
        {
            meta.PushColor(Color.FromHex("#f87171"));
            meta.AddText(Loc.GetString("duty-traits-meta-blocked", ("reason", blockReason)));
            meta.Pop();
        }
        else if (!_selected.Contains(trait.ID) && !CanSelect(trait, out var reason) && reason != null)
        {
            meta.PushColor(Color.FromHex("#fbbf24"));
            meta.AddText(reason);
            meta.Pop();
        }

        DetailMeta.SetMessage(meta);
    }

    private static void AddLine(FormattedMessage message, string text)
    {
        message.AddText(text);
        message.PushNewline();
    }

    private string JobNames(IEnumerable<ProtoId<JobPrototype>> ids)
    {
        return string.Join(", ", ids.Select(id => _prototype.TryIndex(id, out var job) ? job.LocalizedName : id.Id));
    }

